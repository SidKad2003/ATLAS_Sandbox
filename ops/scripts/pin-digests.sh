#!/usr/bin/env bash
# Regenerate compose/shop.pins.yaml from the images the running upstream containers use.
# Run only after a deliberate upgrade has been tested (make up-svc-sim, make run, make test).
set -euo pipefail
cd "$(dirname "$0")/../.."
out=compose/shop.pins.yaml
{
  echo "# Upstream images pinned by digest (generated by ops/scripts/pin-digests.sh, $(date -u '+%d %b %Y'))."
  echo "# The upstream .env tags demo images as latest-<service>, so the digest is the real pin."
  echo "services:"
  for c in $(docker ps --filter label=com.docker.compose.project=svc-sim --format '{{.Names}}' | sort); do
    svc=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.service"}}' "$c")
    img=$(docker inspect -f '{{.Config.Image}}' "$c")
    case "$img" in svc-sim/*|*pgvector*|valkey/valkey:*) continue ;; esac   # svc-sim's own images are pinned in their Dockerfiles/compose
    ref=${img%@*}
    digest=$(docker image inspect -f '{{range .RepoDigests}}{{println .}}{{end}}' "$img" | head -n1 | cut -d@ -f2)
    [ -n "$digest" ] && echo "  $svc: {image: \"$ref@$digest\"}"
  done
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
